#!/usr/bin/env python3
"""Generate read-only register snapshot scripts from ru_extract.py JSON output.

The scripts run on the STOCK firmware (UART root) and use Broadcom's `dw` tool
(/usr/bin/memaccess: `dw <phys_hex> <count>`), printing one line per register.

Safety defaults:
  * only RW (configuration) registers are read. RO status/counters, interrupt status
    and FIFO-type registers can be read-to-clear or pop data (e.g. PLOAM RX FIFOs)
    and are skipped unless --all is given;
  * RAM-type registers are limited to the first --ram-max entries;
  * one script per block, so you only touch blocks that are clocked/powered in the
    current WAN mode. Reading an unclocked block on BCM UBUS can hang the SoC
    (watchdog reboot). The WAN_TOP blocks (bcm_pondrv) are always powered once
    bcm_pondrv has loaded.

Usage: gen_regdump.py regdb/gponstack.json outdir [--all] [--ram-max N]
"""
import sys, json, os, re

args = [a for a in sys.argv[1:] if not a.startswith("--")]
ALL = "--all" in sys.argv
RAM_MAX = 4
if "--ram-max" in sys.argv:
    RAM_MAX = int(sys.argv[sys.argv.index("--ram-max") + 1])
src, outdir = args[0], args[1]
os.makedirs(outdir, exist_ok=True)
mod = os.path.splitext(os.path.basename(src))[0]
blocks = json.load(open(src))
risky = re.compile(r"(ISR|IRQ|INT_STAT|STATUS|CNT|COUNTER|FIFO|PM_|STAT|RD_|POP|MSG)", re.I)
index = []
for b in blocks:
    if not b["bases"]:
        continue
    lines = ["#!/bin/sh", "# %s / block %s - generated by tools/gen_regdump.py (read-only)" % (mod, b["name"]),
             "# Output: <block> <reg> <phys_addr> followed by dw output", ""]
    n = 0
    for inst, base in enumerate(b["bases"]):
        for r in b["regs"]:
            if not ALL:
                if r.get("access") not in (3, 0):  # 3 = RW; 0 = unknown (rdpa: no access info)
                    continue
                if r.get("access") == 0 or risky.search(r["name"] or ""):
                    continue
            cnt = min(r["ram_count"] + 1, RAM_MAX) if r["ram_count"] else 1
            stride = r["stride"] or 4
            for i in range(cnt):
                a = base + r["addr"] + i * stride
                tag = "%s[%d].%s%s" % (b["name"], inst, r["name"], ("[%d]" % i) if r["ram_count"] else "")
                lines.append("echo '%s 0x%08x'; dw %x 1" % (tag, a, a))
                n += 1
    if n:
        fn = "%s__%s.sh" % (mod, b["name"])
        open(os.path.join(outdir, fn), "w").write("\n".join(lines) + "\n")
        index.append("%-60s %4d regs  base 0x%08x" % (fn, n, b["bases"][0]))
open(os.path.join(outdir, "INDEX_%s.txt" % mod), "w").write("\n".join(index) + "\n")
print("%s: %d block scripts" % (mod, len(index)))
